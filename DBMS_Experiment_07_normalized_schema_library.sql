   ALGORITHM
   ---------
   STEP 1 : Start
   STEP 2 : Design the schema for the library system and normalize it
   STEP 3 : Create the tables in the RDBMS
   STEP 4 : Populate the tables with sample data
   STEP 5 : Stop

   ENTITY-RELATIONSHIP DESIGN
   ---------------------------
   Authors        : AuthorID (PK), FirstName, LastName
   Books          : BookID (PK), Title, Genre, PublicationYear
   Borrowers      : BorrowerID (PK), FirstName, LastName, MembershipDate
   BookAuthors    : BookID (FK), AuthorID (FK)               -- M:N Books<->Authors
   BorrowedBooks  : BorrowerID (FK), BookID (FK),
                    BorrowedDate, ReturnDate                 -- M:N Borrowers<->Books

   RELATIONSHIPS
   -------------
   - An author can write multiple books (via BookAuthors)
   - A book can have multiple authors (via BookAuthors)
   - A borrower can borrow multiple books (via BorrowedBooks)
   - A book can be borrowed by multiple borrowers over time (via BorrowedBooks)
   ============================================================================ */


/* ----------------------------------------------------------------------------
   STEP 3 : TABLE CREATION (in dependency order)
   ---------------------------------------------------------------------------- */

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE BorrowedBooks CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE BookAuthors CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE Borrowers CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE Books CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE Authors CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

CREATE TABLE Authors (
    AuthorID  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FirstName VARCHAR2(50),
    LastName  VARCHAR2(50)
);

CREATE TABLE Books (
    BookID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Title           VARCHAR2(100),
    Genre           VARCHAR2(50),
    PublicationYear NUMBER(4)
);

CREATE TABLE BookAuthors (
    BookID   NUMBER,
    AuthorID NUMBER,
    PRIMARY KEY (BookID, AuthorID),
    FOREIGN KEY (BookID)   REFERENCES Books(BookID),
    FOREIGN KEY (AuthorID) REFERENCES Authors(AuthorID)
);

CREATE TABLE Borrowers (
    BorrowerID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FirstName      VARCHAR2(50),
    LastName       VARCHAR2(50),
    MembershipDate DATE
);

CREATE TABLE BorrowedBooks (
    BorrowerID   NUMBER,
    BookID       NUMBER,
    BorrowedDate DATE,
    ReturnDate   DATE,
    PRIMARY KEY (BorrowerID, BookID),
    FOREIGN KEY (BorrowerID) REFERENCES Borrowers(BorrowerID),
    FOREIGN KEY (BookID)     REFERENCES Books(BookID)
);


